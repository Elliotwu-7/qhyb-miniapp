const MESSAGES: Record<AppLocale, Record<string, string>> = { zh: ZH, bo: BO, en: EN }

function savedLocale(): AppLocale {
  let value = ''
  try {
    value = String(uni.getStorageSync(LOCALE_KEY) || '')
    if (value === 'bo' || value === 'en' || value === 'zh') return value
  } catch {
    // Storage is optional; Chinese remains the safe first-run default.
  }
  return 'zh'
}

export const locale = ref<AppLocale>(savedLocale())
export const localeClass = computed(() => `lang-${locale.value}`)

export function t(key: string, vars?: Record<string, string | number>): string {
  let value = SOURCE_MESSAGES[locale.value]?.[key] || SEARCH_MESSAGES[locale.value]?.[key] || CONTENT_MESSAGES[locale.value]?.[key] || MESSAGES[locale.value][key] || ZH[key] || key
  if (vars) {
    Object.keys(vars).forEach((name) => {
      value = value.split(`{${name}}`).join(String(vars[name]))
    })
  }
  return value
}


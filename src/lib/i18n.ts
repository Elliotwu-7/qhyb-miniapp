const ROUTE_TITLES: Record<string, string> = {
  'pages/index/index': 'nav.home', 'pages/me/me': 'nav.me', 'pages/register/register': 'nav.login', 'pages/about/about': 'nav.about', 'pages/detail/detail': 'nav.detail', 'pages/label/label': 'nav.label', 'pages/guide/guide': 'guide.source', 'pages/graph/graph': 'nav.graph', 'pages/ref/ref': 'ref.nav',
}

function currentRoute(): string {
  let pages: Array<{ route?: string }> = []
  let current: { route?: string } | undefined
  let hash = ''
  try {
    pages = getCurrentPages() as Array<{ route?: string }>
    current = pages[pages.length - 1]
    return current?.route || ''
  } catch {
    try {
      hash = String(location.hash || '').replace(/^#\/?/, '').split('?')[0]
      return hash
    } catch {
      return ''
    }
  }
}

function safeCall(fn: () => void) {
  try { fn() } catch { /* unsupported outside a Mini Program */ }
}

export function applyLocaleChrome(routeOverride = '') {
  const route = routeOverride || currentRoute()
  const titleKey = ROUTE_TITLES[route]
  if (titleKey) {
    safeCall(() => uni.setNavigationBarTitle({ title: t(titleKey), fail() {} }))
  }
  safeCall(() => uni.setTabBarItem({ index: 0, text: t('tab.search'), fail() {} }))
  safeCall(() => uni.setTabBarItem({ index: 1, text: t('tab.me'), fail() {} }))
}

export function setLocale(next: AppLocale, route = '') {
  if (next !== 'zh' && next !== 'bo' && next !== 'en') return
  locale.value = next
  if (next === 'bo') ensureTibetanFont()
  try { uni.setStorageSync(LOCALE_KEY, next) } catch { /* keep the in-memory choice */ }
  applyLocaleChrome(route)
  // Some runtimes redraw their native page header after the reactive page update.
  // Apply once more on the next task so that redraw cannot restore pages.json text.
  setTimeout(() => applyLocaleChrome(route), 0)
}

export function bootLocale() {
  locale.value = savedLocale()
  if (locale.value === 'bo') ensureTibetanFont()
  applyLocaleChrome()
}
